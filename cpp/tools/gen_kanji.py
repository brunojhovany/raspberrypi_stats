#!/usr/bin/env python3
"""Rasterize a few kanji to 16x16 bitmaps for the Evangelion-style view.

Usage: python3 tools/gen_kanji.py > cpp/src/kanji16.inc
Needs Pillow and a CJK font (Debian: fonts-droid-fallback).
Each glyph is 16 uint16_t rows; bit 15 is the leftmost pixel.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/droid/DroidSansFallbackFull.ttf"
SIZE = 16
THRESH = 110
# Keep in sync with the K_* enum in portrait.h
GLYPHS = "正常電圧低下システム状態"

font = ImageFont.truetype(FONT, SIZE)
print("// Generated by tools/gen_kanji.py from DroidSansFallbackFull.ttf. Do not edit.")
for ch in GLYPHS:
    im = Image.new("L", (SIZE, SIZE), 0)
    d = ImageDraw.Draw(im)
    bb = font.getbbox(ch)
    d.text(((SIZE - (bb[2] - bb[0])) // 2 - bb[0], (SIZE - (bb[3] - bb[1])) // 2 - bb[1]),
           ch, font=font, fill=255)
    rows = []
    for y in range(SIZE):
        v = 0
        for x in range(SIZE):
            if im.getpixel((x, y)) > THRESH:
                v |= 1 << (15 - x)
        rows.append(f"0x{v:04X}")
    print(f"/* U+{ord(ch):04X} {ch} */ " + ", ".join(rows) + ",")
